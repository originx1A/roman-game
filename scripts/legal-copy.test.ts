test('one shared Privacy Policy and Terms of Use, with game-only purchase terms', () => {
  assert.equal(L.SHARED_PRIVACY_URL, 'https://romansgame.com/privacy')
  assert.equal(L.SHARED_TERMS_URL, 'https://romansgame.com/terms')
  assert.equal(L.POLICY_VERSION, '2026-10-18-draft')
  assert.equal(L.SIGNUP_AGREE, 'I agree to the Terms and Privacy Policy')
  assert.equal(L.signupAgreeLabel(false), L.SIGNUP_AGREE)
  assert.equal(L.signupAgreeLabel(true), L.SIGNUP_AGREE_GUARDIAN)
  assert.match(L.SIGNUP_AGREE_GUARDIAN, /parent or guardian/)
  assert.match(L.SIGNUP_AGREE_GUARDIAN, /I agree to the Terms and Privacy Policy/)
  const use = L.LEGAL_BLOCKS.find((b) => b.id === 'use')
  const purchase = L.LEGAL_BLOCKS.find((b) => b.id === 'terms')
  const privacyBlock = L.LEGAL_BLOCKS.find((b) => b.id === 'privacy')
  assert.equal(use?.title, 'Terms of Use')
  assert.equal(purchase?.title, 'Terms of Purchase')
  assert.match(use?.paragraphs.join(' ') ?? '', /coming separately/)
  assert.match(use?.paragraphs.join(' ') ?? '', /game’s Terms of Purchase/)
  assert.match(purchase?.paragraphs.join(' ') ?? '', /game-only/)
  assert.match(purchase?.paragraphs.join(' ') ?? '', /no cash value/)
  assert.equal(use?.links?.[0]?.href, 'https://romansgame.com/terms')
  assert.equal(privacyBlock?.links?.[0]?.href, 'https://romansgame.com/privacy')
  for (const file of [page, privacy]) {
    assert.match(file, /https:\/\/romansgame\.com\/privacy/)
    assert.match(file, /https:\/\/romansgame\.com\/terms/)
    assert.match(file, /coming separately/)
  }
  assert.match(page, /game-only Terms of Purchase/)
})

test('sign-up has one consent checkbox and records version only in an unapplied migration', async () => {
  assert.match(sheet, /signupAgreeLabel\(!age13\)/)
  assert.match(sheet, /I agree to the /)
  assert.match(sheet, /I am the parent or guardian and I agree to the /)
  assert.match(sheet, /romansgame\.com\/terms/)
  assert.match(sheet, /romansgame\.com\/privacy/)
  assert.match(sheet, /Agree to the Terms and Privacy Policy to make an account/)
  assert.match(cloud, /insert\(\{ id: uid, display_name, age_13_plus: true, marketing_opt_in: consent\.optIn \}\)/)
  assert.doesNotMatch(cloud, /policy_version:|policy_consented_at:|guardian_consent:/)
  assert.match(migration, /NOT APPLIED/)
  assert.match(migration, /policy_version/)
  assert.match(migration, /policy_consented_at/)
  assert.match(migration, /guardian_consent/)
  assert.match(migration, /oelsglmfkpzbueqysvdm/)
  const at = Date.parse('2026-10-18T12:00:00.000Z')
  const row = L.policyConsentRecord(at, true)
  assert.equal(row.policyVersion, '2026-10-18-draft')
  assert.equal(row.consentedAt, '2026-10-18T12:00:00.000Z')
  assert.equal(row.guardian, true)
  assert.equal(L.consentAllowsAccount({ age13: true, policy: L.policyConsentRecord(at, false) }), true)
  assert.equal(L.consentAllowsAccount({ age13: false, policy: L.policyConsentRecord(at, true) }), true)
  assert.equal(L.consentAllowsAccount({ age13: false, policy: L.policyConsentRecord(at, false) }), false)
  assert.equal(L.consentAllowsAccount({ age13: true }), false)
  const kept = L.parseStoredConsent({ age13: true, optIn: true })
  assert.equal(kept?.age13, true)
  assert.equal(kept?.policy, undefined)
  const parsed = L.parseStoredConsent({ age13: false, optIn: false, policy: row })
  assert.equal(parsed?.policy?.guardian, true)
  const store = await import('../netlify/lib/policyConsentStore.ts')
  assert.equal(store.policyConsentWriteEnabled(undefined, true), false)
  assert.equal(store.policyConsentWriteEnabled('1', false), false)
  assert.equal(store.policyConsentWriteEnabled('1', true), true)
  if (process.env.ACCOUNT_LEDGER_ENABLED === '1' && process.env.SUPABASE_SERVICE_ROLE_KEY) {
    assert.fail('refusing to call the live consent write from tests')
  }
  assert.equal(await store.writePolicyConsent('00000000-0000-0000-0000-000000000000', true), false)
})

