import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const sheet = readFileSync(new URL('../src/cloud/CloudScores.tsx', import.meta.url), 'utf8')
const cloud = readFileSync(new URL('../src/cloud/cloud.ts', import.meta.url), 'utf8')
const css = readFileSync(new URL('../src/App.css', import.meta.url), 'utf8')
const app = readFileSync(new URL('../src/App.tsx', import.meta.url), 'utf8')

test('create-account sheet matches the website fields and links', () => {
  assert.match(sheet, /For me/)
  assert.match(sheet, /For my child/)
  assert.match(sheet, /I'm a kid — for me/)
  assert.match(sheet, /Player name or email/)
  assert.match(sheet, /Recovery email \(optional\)/)
  assert.match(sheet, /I'm 13 or older/)
  assert.match(sheet, /Please confirm you are 13 or older\./)
  assert.match(sheet, /Please accept the Terms and Privacy Policy\./)
  assert.match(sheet, /Roman's World News/)
  assert.match(sheet, /href="https:\/\/romansgame\.com\/terms"/)
  assert.match(sheet, /href="https:\/\/romansgame\.com\/privacy"/)
  assert.match(sheet, /postAuth\('\/api\/auth\/signup'/)
  assert.match(sheet, /postAuth\('\/api\/auth\/signin'/)
  assert.match(sheet, /signUpBody\(/)
  assert.doesNotMatch(sheet, /No password/)
  assert.doesNotMatch(sheet, /We'll email you a sign-in link/)
  assert.doesNotMatch(sheet, /oelsglmfkpzbueqysvdm/)
  assert.match(cloud, /https:\/\/oelsglmfkpzbueqysvdm\.supabase\.co/)
})

test('email-link sign-in stays available for existing accounts', () => {
  assert.match(sheet, /Sign in with email link instead/)
  assert.match(sheet, /Tap the link in your email, or enter the code from your email/)
  assert.match(sheet, /aria-label="the code from your email"/)
  assert.match(sheet, /inputMode="numeric"/)
  assert.match(sheet, /maxLength=\{8\}/)
  assert.match(sheet, /verifyEmailCode\(email, code\)/)
  assert.match(cloud, /token\.replace\(\/\\s\/g, ''\)/)
  assert.match(cloud, /\\d\{6,8\}/)
  assert.match(cloud, /verifyOtp\(\{ email: email\.trim\(\), token: code, type: 'email' \}\)/)
  assert.match(cloud, /signInWithOtp/)
  assert.doesNotMatch(sheet, /6-digit/)
  assert.doesNotMatch(cloud, /6-digit/)
})

test('victory save button is the guest prompt and signed-in players use the account name', () => {
  assert.match(sheet, /guestSaveLabel\(cloud\.pending\)/)
  assert.match(sheet, /const hideButton = compact && cloud\.status === 'signed-in'/)
  assert.match(sheet, /Scores saving as \$\{shownName\}/)
  assert.match(sheet, /Player name:/)
  assert.doesNotMatch(sheet, /Signed in as \{cloud\.email\}/)
  assert.match(app, /accountName \|\| cleanPlayerName\(settings\.playerName\)/)
  assert.match(app, /playerName \|\| profile\?\.displayName/)
  assert.doesNotMatch(app, /profile\.displayName\.split\(' '\)\[0\]/)
})

test('the sign-in sheet locks the viewport and pauses a cursor effect', () => {
  assert.match(sheet, /setCursorFxPaused\(true\)/)
  assert.match(sheet, /setCursorFxPaused\(false\)/)
  assert.match(sheet, /100dvh|visualViewport/)
  assert.match(css, /html\.rg-auth-open/)
  assert.match(css, /height: 100dvh/)
  assert.match(css, /safe-area-inset-top/)
  assert.match(css, /safe-area-inset-bottom/)
  assert.match(css, /\.cloud-sheet input[\s\S]*font-size: 16px/)
  assert.match(css, /rg-cursor-fx-paused/)
  assert.match(css, /overflow: hidden !important/)
})
